function [periods, trajectories] = evaluate_two_period_voltage(sourceLoad, config)
%EVALUATE_TWO_PERIOD_VOLTAGE Calculate and pair voltage coordinates by trajectory.
% See 01_IDEA/derivation.md, Sections 1 and 2.
arguments
    sourceLoad table
    config (1,1) struct
end

powerColumns = ["windMW", "solarMW", "loadMW", "windMVAr", "solarMVAr", "loadMVAr"];
requiredColumns = ["trajectoryId", "period", powerColumns];
assert(all(ismember(requiredColumns, string(sourceLoad.Properties.VariableNames))), ...
    "TMMTimeseries:MissingSourceLoadColumns", ...
    "The input CSV must have these columns: %s.", strjoin(requiredColumns, ", "));
sourceLoad.trajectoryId = string(sourceLoad.trajectoryId);
assert(all(~ismissing(sourceLoad.trajectoryId) & strlength(sourceLoad.trajectoryId) > 0), ...
    "TMMTimeseries:MissingTrajectoryId", "Each input row must identify its source/load trajectory.");
assert(height(sourceLoad) >= 2 && mod(height(sourceLoad), 2) == 0, ...
    "TMMTimeseries:InvalidRowCount", "The input CSV must have two rows per trajectory.");

periods = sortrows(sourceLoad, ["trajectoryId", "period"]);
first = 1:2:height(periods);
second = 2:2:height(periods);
trajectoryIds = periods.trajectoryId(first);
assert(isequal(trajectoryIds, periods.trajectoryId(second)) && ...
    numel(unique(trajectoryIds)) == numel(trajectoryIds) && ...
    all(periods.period(first) == 1) && all(periods.period(second) == 2), ...
    "TMMTimeseries:InvalidPeriodPair", ...
    "Each trajectoryId must have exactly one row for period 1 and one for period 2.");
powerValues = periods{:, powerColumns};
assert(isnumeric(powerValues) && isreal(powerValues) && all(isfinite(powerValues), "all"), ...
    "TMMTimeseries:InvalidSourceLoadPower", "All source and load powers must be finite real values.");

periods.pNetMW = periods.windMW + periods.solarMW - periods.loadMW;
periods.qNetMVAr = periods.windMVAr + periods.solarMVAr - periods.loadMVAr;
[voltagePu, periods.powerResidualPu] = TMMTimeseries_core.powerflow.solve_two_bus_voltage( ...
    periods.pNetMW / config.baseMVA, periods.qNetMVAr / config.baseMVA, ...
    complex(config.lineResistancePu, config.lineReactancePu));
assert(max(periods.powerResidualPu) <= config.powerResidualTolerancePu, ...
    "TMMTimeseries:TwoBusPowerResidual", ...
    "The calculated two-bus voltages exceed the prescribed power residual tolerance.");

periods.voltageRealPu = real(voltagePu);
periods.voltageImagPu = imag(voltagePu);
periods.voltageMagnitudePu = abs(voltagePu);
periods.lowVoltage = periods.voltageMagnitudePu < config.voltageMinPu;
trajectories = table(trajectoryIds, real(voltagePu(first)), imag(voltagePu(first)), ...
    real(voltagePu(second)), imag(voltagePu(second)), ...
    periods.lowVoltage(first), periods.lowVoltage(second), ...
    periods.lowVoltage(first) & periods.lowVoltage(second), ...
    VariableNames=["trajectoryId", "voltageReal1Pu", "voltageImag1Pu", ...
    "voltageReal2Pu", "voltageImag2Pu", "low1", "low2", "bothLow"]);
end
